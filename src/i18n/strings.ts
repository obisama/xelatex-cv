/** Localized digits for Arabic UI. */
export function formatNumber(n: number, lang: Language): string {
  if (lang !== 'ar') return String(n);
  return String(n).replace(/\d/g, (d) => '٠١٢٣٤٥٦٧٨٩'[Number(d)]);
}
